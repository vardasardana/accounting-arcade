import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; p.on('console', (m) => { if (m.type() === 'error' || m.type()==='warning') errs.push(m.type()+': '+m.text()); }); p.on('pageerror', (e) => errs.push('PAGEERR ' + e.message + '\n' + e.stack));
await p.goto('http://localhost:4173/');
await p.waitForTimeout(3000);
await p.screenshot({ path: 'shots/_smoke_title.png' });
console.log(await p.evaluate(() => JSON.stringify(window.__AA?.S.report)));
console.log(errs.join('\n'));
await b.close();
